// LocalStorage Keys
const KEYS = {
  BLOGS: "dental_blogs_v2",
  PRODUCTS: "dental_products_v2",
  SETTINGS: "dental_settings_v2",
  CART: "dental_cart_v2"
};

// Data Store Accessors
const DataStore = {
  getBlogs() {
    try {
      const data = localStorage.getItem(KEYS.BLOGS);
      if (data) return JSON.parse(data);
    } catch (e) {
      console.warn("Storage read error:", e);
    }
    localStorage.setItem(KEYS.BLOGS, JSON.stringify(DEFAULT_BLOGS));
    return DEFAULT_BLOGS;
  },

  saveBlog(blog) {
    const blogs = this.getBlogs();
    if (!blog.id) {
      blog.id = "post-" + Date.now();
      blog.slug = blog.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
      blogs.unshift(blog);
    } else {
      const idx = blogs.findIndex(b => b.id === blog.id);
      if (idx !== -1) blogs[idx] = blog;
      else blogs.unshift(blog);
    }
    localStorage.setItem(KEYS.BLOGS, JSON.stringify(blogs));
    return blog;
  },

  deleteBlog(id) {
    let blogs = this.getBlogs();
    blogs = blogs.filter(b => b.id !== id);
    localStorage.setItem(KEYS.BLOGS, JSON.stringify(blogs));
    return blogs;
  },

  getProducts() {
    try {
      const data = localStorage.getItem(KEYS.PRODUCTS);
      if (data) return JSON.parse(data);
    } catch (e) {
      console.warn("Storage read error:", e);
    }
    localStorage.setItem(KEYS.PRODUCTS, JSON.stringify(DEFAULT_PRODUCTS));
    return DEFAULT_PRODUCTS;
  },

  saveProduct(prod) {
    const products = this.getProducts();
    if (!prod.id) {
      prod.id = "prod-" + Date.now();
      products.unshift(prod);
    } else {
      const idx = products.findIndex(p => p.id === prod.id);
      if (idx !== -1) products[idx] = prod;
      else products.unshift(prod);
    }
    localStorage.setItem(KEYS.PRODUCTS, JSON.stringify(products));
    return prod;
  },

  deleteProduct(id) {
    let products = this.getProducts();
    products = products.filter(p => p.id !== id);
    localStorage.setItem(KEYS.PRODUCTS, JSON.stringify(products));
    return products;
  },

  getSettings() {
    try {
      const data = localStorage.getItem(KEYS.SETTINGS);
      if (data) return JSON.parse(data);
    } catch (e) {}
    const defaultSettings = {
      adminPassword: "lathasree2026",
      adsensePublisherId: "",
      adsenseActive: false,
      searchConsoleMeta: "",
      currency: "₹"
    };
    localStorage.setItem(KEYS.SETTINGS, JSON.stringify(defaultSettings));
    return defaultSettings;
  },

  saveSettings(newSettings) {
    const cur = this.getSettings();
    const updated = Object.assign({}, cur, newSettings);
    localStorage.setItem(KEYS.SETTINGS, JSON.stringify(updated));
    return updated;
  },

  // Cart
  getCart() {
    try {
      const data = localStorage.getItem(KEYS.CART);
      if (data) return JSON.parse(data);
    } catch (e) {}
    return [];
  },

  addToCart(productId) {
    const products = this.getProducts();
    const prod = products.find(p => p.id === productId);
    if (!prod) return;
    const cart = this.getCart();
    const existing = cart.find(i => i.id === productId);
    if (existing) {
      existing.quantity += 1;
    } else {
      cart.push({
        id: prod.id,
        name: prod.name,
        price: prod.price,
        image: prod.image,
        quantity: 1
      });
    }
    localStorage.setItem(KEYS.CART, JSON.stringify(cart));
    this.dispatchCartEvent();
  },

  updateCartQty(productId, delta) {
    let cart = this.getCart();
    const item = cart.find(i => i.id === productId);
    if (!item) return;
    item.quantity += delta;
    if (item.quantity <= 0) {
      cart = cart.filter(i => i.id !== productId);
    }
    localStorage.setItem(KEYS.CART, JSON.stringify(cart));
    this.dispatchCartEvent();
  },

  clearCart() {
    localStorage.setItem(KEYS.CART, JSON.stringify([]));
    this.dispatchCartEvent();
  },

  dispatchCartEvent() {
    window.dispatchEvent(new CustomEvent("cart-updated", { detail: this.getCart() }));
  }
};

window.DataStore = DataStore;
